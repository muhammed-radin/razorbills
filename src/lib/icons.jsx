const ICON_CATEGORY_BY_NAME = Object.entries(ICON_GROUPS).reduce(
  (acc, [group, names]) => {
    for (const name of names) {
      if (!acc[name]) acc[name] = group;
    }
    return acc;
  },
  {},
);

const titleCase = (kebab) =>
  kebab
    .split("-")
    .map((part) =>
      part.length <= 3 ? part.toUpperCase() : part.charAt(0).toUpperCase() + part.slice(1),
    )
    .join(" ");

/**
 * Metadata for the admin icon picker: name, category and searchable tags.
 * Shape-compatible with lucide's `iconsData`.
 */
export const ICON_SEARCH_DATA = ICON_NAMES.map((name) => {
  const category = ICON_CATEGORY_BY_NAME[name] || "general";
  return {
    name,
    categories: [category],
    tags: [...name.split("-"), category, titleCase(name).toLowerCase()],
  };
});

export const normalizeIconName = (name) =>
  String(name ?? "")
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/[\s_]+/g, "-")
    .toLowerCase()
    .trim();

/** Resolve an icon name (kebab/camel/Pascal) to a lucide component. */
export function resolveIcon(...candidates) {
  for (const candidate of candidates) {
    if (!candidate) continue;
    const key = normalizeIconName(candidate);
    if (!key) continue;
    if (ICON_REGISTRY[key]) return ICON_REGISTRY[key];
    const alias = ICON_ALIASES[key];
    if (alias && ICON_REGISTRY[alias]) return ICON_REGISTRY[alias];
  }
  return Folder;
}

/**
 * Resolve an icon by loose substring match, e.g. a category named
 * "Smartphones & Tablets" will match the `smartphone` icon.
 */
export function iconFor(value, fallback = Folder) {
  const raw = normalizeIconName(value);
  if (!raw) return fallback;
  const direct = resolveIcon(raw);
  if (direct !== Folder) return direct;
  for (const token of raw.split("-")) {
    if (token.length < 3) continue;
    const match = ICON_NAMES.find((name) => name.includes(token));
    if (match) return ICON_REGISTRY[match];
  }
  return fallback;
}

/** Renders the icon for `name`, falling back to `fallback`. */
export function AppIcon({ name, fallback = Folder, ...props }) {
  const Component = resolveIcon(name);
  const Resolved = Component === Folder && fallback ? fallback : Component;
  return <Resolved {...props} />;
}

export default ICON_REGISTRY;
